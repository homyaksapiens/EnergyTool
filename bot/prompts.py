def format_context(chunks) -> str:
    return "\n\n".join(f"[{i}] {c.title}\n{c.text}" for i, c in enumerate(chunks, 1))


def build_system(chunks) -> str:
    # replace, а не format: в тексте материалов могут встретиться фигурные скобки
    return SYSTEM_PROMPT.replace("{context}", format_context(chunks))
